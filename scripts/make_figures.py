#!/usr/bin/env python3
"""Regenerate the code-generated publication figures from the authoritative theory.

No equation is duplicated here -- every curve is computed by calling
closed_mitosis_mechanics.theory / .robustness / .parameters. PNG only
(no PDF), dpi=300, exactly one final file per figure (no "_clean" copies).

Figure 1 is a manual schematic and is not generated by this script. This
module generates the analytical figures and the deterministic OAT sensitivity
figure; generated image files are excluded from version control.
"""

from __future__ import annotations

import sys
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
from matplotlib.patches import Patch

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "src"))

from closed_mitosis_mechanics import load_baseline, load_confinement_range_pa  # noqa: E402
from closed_mitosis_mechanics.robustness import deterministic_oat  # noqa: E402
from closed_mitosis_mechanics.theory import (  # noqa: E402
    THRESHOLD_STATUS_BASELINE_SUPERTHRESHOLD,
    THRESHOLD_STATUS_POSITIVE_CROSSING,
    exact_elasticities,
    f0_zero_pressure,
    mu_margin,
    p_star,
    q_star_exact,
)

MAIN_DIR = REPO_ROOT / "figures" / "main"
SUPP_DIR = REPO_ROOT / "figures" / "supplementary"
DPI = 300

BLUE = "#236192"
RED = "#B33A3A"
GOLD = "#C58B2A"
GREEN = "#3A7D6B"
GREY = "#767F89"
PALE_GREY = "#E3E6E9"


def _style() -> None:
    plt.rcParams.update(
        {
            "font.family": "DejaVu Sans",
            "font.size": 10,
            "axes.labelsize": 11,
            "axes.titlesize": 12,
            "legend.fontsize": 8.5,
            "axes.spines.top": False,
            "axes.spines.right": False,
        }
    )


def _save(fig: plt.Figure, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path, dpi=DPI, bbox_inches="tight", facecolor="white")
    plt.close(fig)
    print(f"wrote {path.relative_to(REPO_ROOT)}")


def figure_02_dimensionless_threshold() -> None:
    """Feasibility-boundary plot: mu on x, chi on y, boundary chi=q*(mu)."""
    baseline = load_baseline()
    mu_baseline = mu_margin(baseline.buckling_force_n, baseline.kappa_effective_ne_j, baseline.sigma_effective_ne_npm)

    mu_axis = np.linspace(1.0, 3.0, 500)
    chi_boundary = np.array([q_star_exact(m) for m in mu_axis])
    chi_baseline = q_star_exact(mu_baseline)
    y_lo, y_hi = -3.0, 58.0

    fig, ax = plt.subplots(figsize=(6.2, 4.6))

    ax.fill_between(mu_axis, chi_boundary, y_hi, color=GREEN, alpha=0.12, zorder=0)
    ax.fill_between(mu_axis, y_lo, chi_boundary, color=GREY, alpha=0.14, zorder=0)
    ax.plot(mu_axis, chi_boundary, color=BLUE, lw=2.4, zorder=3)
    ax.axvline(1.0, color=GREY, lw=1.2, ls="--", ymax=0.9, zorder=2)
    ax.axvline(mu_baseline, color=RED, lw=1.2, ls=(0, (4, 3)), ymax=0.9, zorder=2)
    ax.scatter([mu_baseline], [chi_baseline], color=RED, s=50, zorder=5)
    ax.annotate(
        rf"illustrative baseline: $\mu\approx{mu_baseline:.3f}$",
        xy=(mu_baseline, chi_baseline),
        xytext=(2.15, 15.0),
        arrowprops={"arrowstyle": "->", "color": RED},
        color=RED,
        fontsize=8.5,
    )

    ax.text(1.6, 26.0, "threshold-compatible", color="#1f5c46", fontsize=9, fontweight="bold", ha="center")
    ax.text(2.5, 8.0, "below threshold", color="#555555", fontsize=9, fontweight="bold", ha="center")

    ax.set_xlim(1.0, 3.0)
    ax.set_ylim(y_lo, y_hi)
    ax.set_xlabel(r"$\mu = F_b/f_0$")
    ax.set_ylabel(r"$\chi$ (dimensionless)")
    ax.set_title(r"Feasibility boundary: $\chi \geq q^*(\mu)$")
    ax.text(
        0.03,
        0.95,
        r"$q^*(\mu)$ is increasing and convex for $\mu>1$",
        transform=ax.transAxes,
        fontsize=8,
        va="top",
        color="#333333",
    )
    ax.grid(color=PALE_GREY, lw=0.5)

    _save(fig, MAIN_DIR / "fig02_dimensionless_threshold.png")


def figure_03_exact_sensitivity() -> None:
    baseline = load_baseline()
    kappa_j, sigma_npm, buckling_n = (
        baseline.kappa_effective_ne_j,
        baseline.sigma_effective_ne_npm,
        baseline.buckling_force_n,
    )
    mu_baseline = mu_margin(buckling_n, kappa_j, sigma_npm)
    baseline_e = exact_elasticities(mu_baseline)

    fig, axes = plt.subplots(1, 2, figsize=(9.6, 4.2))

    # Panel A: exact elasticities vs mu, focused around the illustrative baseline.
    ax = axes[0]
    mu_axis = np.linspace(1.02, 1.6, 400)
    e_fb = np.array([exact_elasticities(m)["F_b"] for m in mu_axis])
    e_kappa = np.array([exact_elasticities(m)["kappa"] for m in mu_axis])
    e_sigma = np.array([exact_elasticities(m)["sigma"] for m in mu_axis])
    ax.plot(mu_axis, e_fb, color=GOLD, lw=2.0, label=r"$E_{F_b}$")
    ax.plot(mu_axis, e_kappa, color=BLUE, lw=2.0, label=r"$E_{\kappa}$")
    ax.plot(mu_axis, e_sigma, color=GREEN, lw=2.0, label=r"$E_{\sigma}$")
    ax.axhline(0, color=PALE_GREY, lw=1.0)
    ax.scatter(
        [mu_baseline] * 3,
        [baseline_e["F_b"], baseline_e["kappa"], baseline_e["sigma"]],
        color=[GOLD, BLUE, GREEN],
        edgecolor="white",
        s=45,
        zorder=5,
    )
    ax.axvline(mu_baseline, color=RED, lw=1.1, ls=(0, (4, 3)))
    ax.text(mu_baseline + 0.015, 38.5, rf"$\mu\approx{mu_baseline:.3f}$", color=RED, fontsize=7.5, va="top", ha="left")
    ax.set_xlim(1.02, 1.6)
    ax.set_ylim(-15.0, 40.0)
    ax.set_xlabel(r"$\mu = F_b/f_0$")
    ax.set_ylabel("Exact local elasticity")
    ax.set_title(r"Elasticities diverge as $\mu \to 1^+$")
    ax.set_title("A", loc="left", fontsize=14, fontweight="bold")
    ax.text(
        0.97,
        0.04,
        rf"baseline: $E_{{F_b}}\approx{baseline_e['F_b']:.2f}$, $E_\kappa\approx{baseline_e['kappa']:.2f}$, "
        rf"$E_\sigma\approx{baseline_e['sigma']:.2f}$",
        transform=ax.transAxes,
        ha="right",
        va="bottom",
        fontsize=7.2,
        color="#333333",
    )
    ax.legend(loc="upper right", fontsize=8)
    ax.grid(color=PALE_GREY, lw=0.5)

    # Panel B: p*(F_b), log scale, with F_b<f0 hatched as the no-crossing regime.
    ax = axes[1]
    f0_pn = f0_zero_pressure(kappa_j, sigma_npm) * 1.0e12
    fb_axis_pn = np.linspace(20.0, 50.0, 500)
    p_axis_pa = np.full_like(fb_axis_pn, np.nan)
    for i, fb_pn in enumerate(fb_axis_pn):
        result = p_star(kappa_j, sigma_npm, fb_pn * 1.0e-12)
        if result.threshold_status == THRESHOLD_STATUS_POSITIVE_CROSSING:
            p_axis_pa[i] = result.p_star_pa
    ax.axvspan(
        fb_axis_pn.min(),
        f0_pn,
        color="#555555",
        alpha=0.30,
        hatch="////",
        label=r"$F_b<f_0$: no positive-pressure crossing",
    )
    ax.plot(fb_axis_pn, p_axis_pa, color=BLUE, lw=2.2, label=r"$p^*(F_b)$")
    baseline_result = p_star(kappa_j, sigma_npm, buckling_n)
    ax.axvline(baseline.buckling_force_pn, color=RED, lw=1.1, ls=(0, (4, 3)))
    ax.scatter([baseline.buckling_force_pn], [baseline_result.p_star_pa], color=RED, s=55, zorder=5)
    ax.annotate(
        rf"baseline: {baseline.buckling_force_pn:.0f} pN $\to$ $p^*\approx${baseline_result.p_star_pa:.0f} Pa"
        "\n"
        "(effective-pressure threshold)",
        xy=(baseline.buckling_force_pn, baseline_result.p_star_pa),
        xytext=(38.0, 15.0),
        ha="left",
        arrowprops={"arrowstyle": "->", "color": RED},
        color=RED,
        fontsize=7.6,
    )
    ax.set_xlim(20.0, 50.0)
    ax.set_yscale("log")
    ax.set_xlabel(r"$F_b$ (pN)")
    ax.set_ylabel(r"$p^*$ (Pa, log scale)")
    ax.set_title(r"$p^*(F_b)$: calibration fragility")
    ax.set_title("B", loc="left", fontsize=14, fontweight="bold")
    ax.legend(loc="upper left", fontsize=7.5)
    ax.grid(axis="y", which="both", color=PALE_GREY, lw=0.5)

    fig.suptitle(r"Exact sensitivity of $p^*$ near $\mu=1$", y=1.02, fontsize=12.5, fontweight="bold")
    fig.tight_layout()
    _save(fig, MAIN_DIR / "fig03_exact_sensitivity.png")


def figure_04_transmission_feasibility() -> None:
    baseline = load_baseline()
    kappa_j, sigma_npm = baseline.kappa_effective_ne_j, baseline.sigma_effective_ne_npm
    sorce_low_pa, sorce_high_pa = load_confinement_range_pa()

    fb_axis_pn = np.linspace(22.0, 45.0, 260)
    pressure_axis_pa = np.linspace(50.0, 1200.0, 320)

    p_star_pa = np.full_like(fb_axis_pn, np.nan)
    status = np.empty_like(fb_axis_pn, dtype=object)
    for i, fb_pn in enumerate(fb_axis_pn):
        result = p_star(kappa_j, sigma_npm, fb_pn * 1.0e-12)
        status[i] = result.threshold_status
        if result.threshold_status == THRESHOLD_STATUS_POSITIVE_CROSSING:
            p_star_pa[i] = result.p_star_pa

    tcrit = p_star_pa[:, None] / pressure_axis_pa[None, :]

    fig, ax = plt.subplots(figsize=(7.6, 5.0))
    from matplotlib.colors import LinearSegmentedColormap

    cmap = LinearSegmentedColormap.from_list("feasible", ["#DCEBF3", "#F7E7BE", "#E7A09A"])
    # T_crit is a *required transmission fraction*; T in [0,1] physically, so
    # T_crit>1 is not "harder", it is infeasible. Mask it out of the continuous
    # color scale entirely and hatch it instead, rather than extending the
    # gradient past 1 as if it were just a deeper shade of the same thing.
    tcrit_feasible = np.ma.masked_where(tcrit > 1.0, tcrit)
    mesh = ax.pcolormesh(pressure_axis_pa, fb_axis_pn, tcrit_feasible, cmap=cmap, shading="auto", vmin=0, vmax=1.0)
    infeasible = (tcrit > 1.0).astype(float)
    ax.contourf(
        pressure_axis_pa,
        fb_axis_pn,
        infeasible,
        levels=[0.5, 1.5],
        colors=["#8A8A8A"],
        hatches=["////"],
        alpha=0.35,
    )
    cs = ax.contour(pressure_axis_pa, fb_axis_pn, tcrit, levels=[1.0], colors=["white"], linewidths=[2.0])
    ax.clabel(cs, fmt={1.0: r"$T_{\mathrm{crit}}=1$"}, inline=True, fontsize=8, colors=["black"])

    legend_handles = []
    superthreshold_mask = status == THRESHOLD_STATUS_BASELINE_SUPERTHRESHOLD
    if superthreshold_mask.any():
        fb_super = fb_axis_pn[superthreshold_mask]
        # Lighter styling than the T_crit>1 hatch: flat pale fill, no hatch --
        # this is a different kind of "not applicable" (mu<=1, not T_crit>1).
        ax.axhspan(fb_super.min(), fb_super.max(), color="#CFCFCF", alpha=0.55)
        legend_handles.append(
            Patch(facecolor="#CFCFCF", edgecolor="none", alpha=0.55, label=r"$\mu\leq1$: no confinement-induced crossing")
        )
    legend_handles.append(
        Patch(
            facecolor="#8A8A8A",
            edgecolor="none",
            alpha=0.35,
            hatch="////",
            label=r"$T_{\mathrm{crit}}>1$: infeasible for $0\leq T\leq1$",
        )
    )

    ax.axvspan(sorce_low_pa, sorce_high_pa, facecolor="none", edgecolor=GREY, linewidth=1.0, linestyle=(0, (3, 2)))
    # Kept visually secondary (thin, grey, small type): this range is context
    # only, from a different species/tissue, not an S. pombe measurement.
    range_label_y = fb_axis_pn.max() - 2.0
    ax.text(
        (sorce_low_pa + sorce_high_pa) / 2,
        range_label_y,
        "MDCK mitotic rounding-pressure scale (context only)\nnot an $S.\\ pombe$ measurement",
        ha="center",
        va="top",
        fontsize=6.8,
        color="black",
    )

    baseline_fb_pn = baseline.buckling_force_pn
    ax.axhline(baseline_fb_pn, color=BLUE, lw=1.3, ls="--")
    ax.text(
        250.0,
        baseline_fb_pn + 0.6,
        rf"illustrative baseline $F_b$ = {baseline_fb_pn:.0f} pN",
        ha="left",
        va="bottom",
        fontsize=7.8,
        color=BLUE,
        fontweight="bold",
    )

    ax.set_xlabel(r"$p_{\mathrm{confine}}$ (Pa)")
    ax.set_ylabel(r"$F_b$ (pN)")
    ax.set_title(r"Transmission feasibility: $T_{\mathrm{crit}} = p^*(F_b)/p_{\mathrm{confine}}$")
    cb = fig.colorbar(mesh, ax=ax, pad=0.02)
    cb.set_label(r"$T_{\mathrm{crit}}$ (required transmission fraction)")
    ax.legend(handles=legend_handles, loc="lower right", fontsize=7.2, framealpha=0.9)
    _save(fig, MAIN_DIR / "fig04_transmission_feasibility.png")


def figure_s01_parameter_robustness() -> None:
    baseline = load_baseline()
    rows = deterministic_oat(baseline)
    baseline_p_star_pa = next(r.p_star_pa for r in rows if r.parameter == "F_b" and r.perturbation_fraction == 0.0)

    fig, ax = plt.subplots(figsize=(7.2, 4.6))
    markers = {"kappa": "o", "sigma": "s", "F_b": "^"}
    colors = {"kappa": BLUE, "sigma": GREEN, "F_b": RED}
    labels = {"kappa": r"$\kappa_{\mathrm{eff}}$", "sigma": r"$\sigma_{\mathrm{eff}}$", "F_b": r"$F_b$"}
    any_super = False
    for parameter in ("kappa", "sigma", "F_b"):
        subset = [r for r in rows if r.parameter == parameter]
        x = [100.0 * r.perturbation_fraction for r in subset]
        y = [r.p_star_pa if r.threshold_status == THRESHOLD_STATUS_POSITIVE_CROSSING else np.nan for r in subset]
        ax.plot(x, y, marker=markers[parameter], color=colors[parameter], lw=1.8, label=labels[parameter])
        for r in subset:
            if r.threshold_status == THRESHOLD_STATUS_BASELINE_SUPERTHRESHOLD:
                any_super = True
                ax.scatter([100.0 * r.perturbation_fraction], [0.0], marker="x", color=colors[parameter], s=45, zorder=5)
    if any_super:
        ax.scatter([], [], marker="x", color="black", label="no confinement-induced crossing")
    ax.scatter([0.0], [baseline_p_star_pa], marker="*", color="black", s=140, zorder=6, label=rf"common baseline $p^*\approx{baseline_p_star_pa:.2f}$ Pa")
    ax.set_xlabel("One-at-a-time perturbation (%)")
    ax.set_ylabel(r"$p^*$ (Pa)")
    ax.set_title("Deterministic OAT stress tests (not confidence intervals)")
    ax.legend(ncol=2, fontsize=7.5, loc="upper left")
    ax.grid(color=PALE_GREY, lw=0.5)
    _save(fig, SUPP_DIR / "figS01_parameter_robustness.png")


def main() -> int:
    _style()
    MAIN_DIR.mkdir(parents=True, exist_ok=True)
    SUPP_DIR.mkdir(parents=True, exist_ok=True)
    figure_02_dimensionless_threshold()
    figure_03_exact_sensitivity()
    figure_04_transmission_feasibility()
    figure_s01_parameter_robustness()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
